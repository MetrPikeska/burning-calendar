"""Build video/assets/data.json from the web app's static JSON (read only).

Run from the repo root: python3 video/scripts/build_data.py
Every number the video shows comes from this file.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "web/public/data/v1"
OUT = ROOT / "video/assets/data.json"

YEARS = range(2001, 2026)  # full calendar years only


def annual(months: list[dict]) -> list[dict]:
    rows = []
    for y in YEARS:
        ms = [m for m in months if m["ym"].startswith(f"{y}-")]
        assert len(ms) == 12, (y, len(ms))

        def total(key: str) -> float | None:
            vals = [m[key] for m in ms]
            if any(v is None for v in vals):
                return None
            return round(sum(vals), 1)

        backcast = any(m["src"] != "observed" for m in ms)
        rows.append(
            {
                "year": y,
                "modis": total("modis"),
                "viirs": total("viirs"),
                "harm": total("harm"),
                # Sum of monthly 10th/90th percentile bounds: a conservative
                # envelope, wider than a proper annual interval.
                "harm_lo": total("harm_lo") if backcast else None,
                "harm_hi": total("harm_hi") if backcast else None,
                # The naive stitch a user gets by switching sensors in 2012.
                "naive": total("modis") if y < 2012 else total("viirs"),
            }
        )
    return rows


def main() -> None:
    gr = json.loads((DATA / "gr/regions/GR.json").read_text())
    ar = json.loads((DATA / "ar/regions/30.json").read_text())
    gr_index = json.loads((DATA / "gr/index.json").read_text())
    ar_index = json.loads((DATA / "ar/index.json").read_text())

    years = annual(gr["months"])
    fit = [r for r in years if 2012 <= r["year"] <= 2019]
    ratio = sum(r["viirs"] for r in fit) / sum(r["modis"] for r in fit)

    aug = next(m for m in ar["months"] if m["ym"] == "2020-08")
    el64 = json.loads((DATA / "gr/regions/EL64.json").read_text())
    evia = next(m for m in el64["months"] if m["ym"] == "2021-08")
    gr_val = gr["validation"]
    ar_val = ar_index["regions"][0]

    out = {
        "source": "web/public/data/v1, method " + gr_index["method_version"],
        "greece": {
            "annual": years,
            "viirs_over_modis_2012_2019": round(ratio, 2),
            "jump_2011_2012": {
                "modis_2011": next(r["modis"] for r in years if r["year"] == 2011),
                "viirs_2012": next(r["viirs"] for r in years if r["year"] == 2012),
            },
            "loyo_annual_mdape_pct": gr_val["loyo"]["annual_mdape_pct"],
            "peak_hit_harm": gr_val["loyo"]["season"]["harm"]["peak_hit_rate"],
            "peak_hit_modis_raw": gr_val["loyo"]["season"]["modis_raw"]["peak_hit_rate"],
        },
        "argentina": {
            "loyo_annual_mdape_pct": ar_val["loyo_mdape_pct"],
            "peak_hit_harm": ar_val["peak_hit_rate"],
            "peak_hit_modis_raw": ar_val["peak_hit_rate_raw"],
        },
        "entre_rios_aug_2020": {
            "region": ar["name"],
            "viirs": aug["viirs"],
            "baseline_median": aug["baseline_median"],
            "baseline_years": aug["baseline_years"],
            "times_median": round(aug["viirs"] / aug["baseline_median"]),
        },
        # Same numbers the MCP tool get_anomalies {region_id: EL64, year: 2021}
        # returned from production on 14 Nov 2026 (ratio_to_median 67.1).
        "mcp_evia_aug_2021": {
            "region": el64["name"],
            "value": round(evia["harm"]),
            "baseline_median": evia["baseline_median"],
            "baseline_years": evia["baseline_years"],
            "ratio_to_median": round(evia["harm"] / evia["baseline_median"], 1),
            "anom": evia["anom"],
            "view_url": "burning-calendar.vercel.app/?country=gr&region=EL64&from=2021-01&to=2021-12",
            "tools": 15,
        },
    }
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    # HyperFrames forbids fetch at render time, so the scenes read a global.
    OUT.with_suffix(".js").write_text(
        "// Generated by video/scripts/build_data.py, do not edit.\nwindow.BC_DATA = "
        + json.dumps(out, ensure_ascii=False)
        + ";\n"
    )
    print(json.dumps({k: v for k, v in out["greece"].items() if k != "annual"}, indent=1))
    print(out["argentina"], out["entre_rios_aug_2020"])


if __name__ == "__main__":
    main()
