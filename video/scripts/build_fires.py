"""Build video/assets/fires.js: Greek VIIRS detections, 15 Jul - 31 Aug 2021, and the NUTS2 outline.

Run from the repo root: uv run python video/scripts/build_fires.py
Reads data/interim/gr_detections.parquet (type 0, static sources removed, assigned
to regions by the pipeline) and web/public/data/v1/gr/regions.geojson. Read only.
"""

import json
import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "video/assets/fires.js"
START, END = "2021-07-15", "2021-08-31"

# Equirectangular projection fitted to Greece on a 1920 x 1080 frame.
LON0, LAT0 = 24.3, 38.3
K = 128.0  # px per degree of latitude
COSL = math.cos(math.radians(LAT0))
CX, CY = 1010.0, 560.0


def project(lon: float, lat: float) -> tuple[float, float]:
    return round(CX + (lon - LON0) * COSL * K, 1), round(CY - (lat - LAT0) * K, 1)


def main() -> None:
    d = pd.read_parquet(ROOT / "data/interim/gr_detections.parquet")
    v = d[(d.sensor == "viirs") & (d.acq_date >= START) & (d.acq_date <= END)].copy()
    v["day"] = (v.acq_date - pd.Timestamp(START)).dt.days
    v = v.sort_values(["day", "daynight"])
    pts = [[*project(lo, la), int(dy)] for lo, la, dy in zip(v.longitude, v.latitude, v.day)]

    g = json.loads((ROOT / "web/public/data/v1/gr/regions.geojson").read_text())
    rings = []
    for f in g["features"]:
        for poly in f["geometry"]["coordinates"]:
            for ring in poly:
                rings.append([project(lo, la) for lo, la in ring])

    days = int((pd.Timestamp(END) - pd.Timestamp(START)).days) + 1
    out = {"start": START, "days": days, "n": len(pts), "points": pts, "rings": rings}
    OUT.write_text(
        "// Generated by video/scripts/build_fires.py, do not edit.\nwindow.BC_FIRES = "
        + json.dumps(out, separators=(",", ":"))
        + ";\n"
    )
    xs = [p[0] for r in rings for p in r]
    ys = [p[1] for r in rings for p in r]
    print(f"{len(pts)} detections over {days} days; outline x {min(xs)}..{max(xs)}, y {min(ys)}..{max(ys)}")
    print(v.groupby(v.acq_date.dt.strftime("%m-%d")).size().nlargest(5).to_dict())


if __name__ == "__main__":
    main()
