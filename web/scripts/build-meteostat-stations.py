#!/usr/bin/env python3
"""Write web/api/_lib/live/meteostat-stations.ts: Meteostat stations in Greece and Argentina
with observed (not model) data since 2020, for the MCP tool get_weather_stations.

Usage: python3 scripts/build-meteostat-stations.py [path/to/stations.db]
Without a path it downloads https://data.meteostat.net/stations.db (33 MB) to a temp dir.
Stdlib only. Meteostat data: CC BY 4.0 (https://dev.meteostat.net/license).
"""
import json
import sqlite3
import sys
import tempfile
import urllib.request
from datetime import date
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "api" / "_lib" / "live" / "meteostat-stations.ts"
URL = "https://data.meteostat.net/stations.db"
# Providers that carry station observations. dwd_mosmix and metno_forecast are model forecasts.
OBS = ("metar", "dwd_poi", "isd_lite", "ghcnd", "climat", "synop")
PARAMS = ("temp", "tmax", "prcp", "wspd")
MIN_END = "2020-01-01"


def main() -> None:
    if len(sys.argv) > 1:
        db = Path(sys.argv[1])
    else:
        db = Path(tempfile.mkdtemp()) / "stations.db"
        req = urllib.request.Request(URL, headers={"User-Agent": "burning-calendar-build/0.1"})
        with urllib.request.urlopen(req, timeout=120) as r, open(db, "wb") as f:
            f.write(r.read())
    con = sqlite3.connect(db)
    q = f"""
      select s.id, s.country, s.latitude, s.longitude, s.elevation,
             coalesce(n.name, s.id), min(i.start), max(i.end)
      from stations s
      join inventory i on i.station = s.id
      left join names n on n.station = s.id and n.language = 'en'
      where s.country in ('GR', 'AR')
        and i.provider in ({','.join('?' * len(OBS))})
        and i.parameter in ({','.join('?' * len(PARAMS))})
      group by s.id
      having max(i.end) >= ?
      order by s.country, s.id
    """
    rows = con.execute(q, (*OBS, *PARAMS, MIN_END)).fetchall()
    stations = [
        {"id": r[0], "country": r[1], "lat": round(r[2], 4), "lon": round(r[3], 4), "elev": r[4],
         "name": r[5].replace("\n", " ")[:60], "obs_start": r[6], "obs_end": r[7]}
        for r in rows
    ]
    body = ",\n".join("  " + json.dumps(s, ensure_ascii=False) for s in stations)
    OUT.write_text(
        "// Generated by web/scripts/build-meteostat-stations.py on " + date.today().isoformat() + ". Do not edit.\n"
        "// Meteostat stations in GR and AR with observed data (not model) since " + MIN_END + ". CC BY 4.0, Meteostat.\n"
        "export interface MeteostatStation { id: string; country: \"GR\" | \"AR\"; lat: number; lon: number;\n"
        "  elev: number | null; name: string; obs_start: string | null; obs_end: string | null }\n"
        "export const METEOSTAT_STATIONS: MeteostatStation[] = [\n" + body + ",\n];\n",
        encoding="utf-8",
    )
    by = {c: sum(1 for s in stations if s["country"] == c) for c in ("GR", "AR")}
    print(f"{OUT}: {len(stations)} stations {by}")


if __name__ == "__main__":
    main()
